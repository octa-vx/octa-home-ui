export type MessageKey = keyof typeof messages.en;

export function translate(language: string, key: MessageKey, params: Record<string, string> = {}): string {
  const table = language.toLowerCase().startsWith('de') ? messages.de : messages.en;
  return table[key].replace(/\{(\w+)\}/g, (placeholder, name: string) => params[name] ?? placeholder);
}
